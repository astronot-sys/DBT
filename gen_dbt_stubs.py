"""Generate dbt sources, staging models, export models and tests from the load report.

Run after extract_load.py:  python gen_dbt_stubs.py [--export a,b]

Staging models standardise text (trim, empty -> NULL). Export models are the
curated tables that get published to the lake. Replace the generated export SQL
with real business logic as the demo grows; re-running this script overwrites
generated files, so copy a model elsewhere before editing it by hand.
"""
from __future__ import annotations

import argparse
import json
from typing import Any

import yaml

from common import CATALOG_PATH, DBT_DIR

STAGING_DIR = DBT_DIR / "models" / "staging"
EXPORT_DIR = DBT_DIR / "models" / "export"
GENERATED_PATTERNS = ("stg_*.sql", "exp_*.sql", "_sources.yml", "_staging.yml", "_export.yml")


def _clean() -> None:
    for folder in (STAGING_DIR, EXPORT_DIR):
        folder.mkdir(parents=True, exist_ok=True)
        for pattern in GENERATED_PATTERNS:
            for path in folder.glob(pattern):
                path.unlink()


def staging_sql(table: dict[str, Any]) -> str:
    lines: list[str] = []
    for col in table["columns"]:
        quoted = f'"{col["name"]}"'
        if col["kind"] == "text":
            lines.append(f"nullif(trim({quoted}), '') as {quoted}")
        else:
            lines.append(quoted)
    body = ",\n    ".join(lines)
    return (
        "-- Generated by gen_dbt_stubs.py: trims text and turns empty strings into NULL.\n"
        "select\n    " + body + "\nfrom {{ source('raw', '" + table["raw_table"] + "') }}\n"
    )


def export_sql(table: dict[str, Any]) -> str:
    return (
        "-- Generated by gen_dbt_stubs.py: curated output published to the data lake.\n"
        "{{ config(materialized='table') }}\n\n"
        "select\n"
        "    s.*,\n"
        "    '{{ invocation_id }}' as _dbt_invocation_id,\n"
        "    current_timestamp as _built_at\n"
        "from {{ ref('stg_" + table["raw_table"] + "') }} as s\n"
    )


def _model_yaml(name: str, description: str, pk: list[str]) -> dict[str, Any]:
    model: dict[str, Any] = {"name": name, "description": description}
    if len(pk) == 1:
        model["columns"] = [{"name": pk[0], "data_tests": ["unique", "not_null"]}]
    return model


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--export", help="Comma-separated raw table names to export (default: all)")
    args = parser.parse_args()

    catalog = json.loads(CATALOG_PATH.read_text(encoding="utf-8"))
    tables: list[dict[str, Any]] = catalog["tables"]
    export_filter = {t.strip().lower() for t in args.export.split(",")} if args.export else None
    export_tables = [t for t in tables if export_filter is None or t["raw_table"] in export_filter]
    if not export_tables:
        raise SystemExit("No tables selected for export. Check --export names (use raw table names).")

    _clean()

    sources = {
        "version": 2,
        "sources": [
            {"name": "raw", "schema": "raw", "tables": [{"name": t["raw_table"]} for t in tables]}
        ],
    }
    (STAGING_DIR / "_sources.yml").write_text(yaml.safe_dump(sources, sort_keys=False), encoding="utf-8")

    staging_models = [
        _model_yaml(f"stg_{t['raw_table']}", f"Standardised copy of {t['source_table']}", t["primary_key"])
        for t in tables
    ]
    (STAGING_DIR / "_staging.yml").write_text(
        yaml.safe_dump({"version": 2, "models": staging_models}, sort_keys=False), encoding="utf-8"
    )
    for t in tables:
        (STAGING_DIR / f"stg_{t['raw_table']}.sql").write_text(staging_sql(t), encoding="utf-8")

    export_models = [
        _model_yaml(f"exp_{t['raw_table']}", f"Curated {t['source_table']} published to the lake", t["primary_key"])
        for t in export_tables
    ]
    (EXPORT_DIR / "_export.yml").write_text(
        yaml.safe_dump({"version": 2, "models": export_models}, sort_keys=False), encoding="utf-8"
    )
    for t in export_tables:
        (EXPORT_DIR / f"exp_{t['raw_table']}.sql").write_text(export_sql(t), encoding="utf-8")

    pk_tests = sum(1 for t in tables if len(t["primary_key"]) == 1)
    print(
        f"Generated {len(tables)} staging and {len(export_tables)} export model(s); "
        f"{pk_tests} table(s) have primary-key tests."
    )


if __name__ == "__main__":
    main()
